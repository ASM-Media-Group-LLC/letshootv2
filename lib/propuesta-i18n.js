/** Devuelve el diccionario para un idioma (fallback es). */
export function propDict(lang) {
  return PROP[lang] || PROP.es;
}

/** Hook: sigue el idioma del sitio salvo que se fuerce uno. */
export function useProp(forceLang) {
  const { lang } = useLang();
  const use = forceLang || (PROP[lang] ? lang : 'es');
  return propDict(use);
}
